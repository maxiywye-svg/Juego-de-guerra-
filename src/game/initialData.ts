export function getSectorAt(x: number, y: number): SectorInfo {
  for (const s of SECTORS) {
    if (
      x >= s.bounds.x &&
      x <= s.bounds.x + s.bounds.w &&
      y >= s.bounds.y &&
      y <= s.bounds.y + s.bounds.h
    ) {
      return s;
    }
  }
  return SECTORS[0];
}

